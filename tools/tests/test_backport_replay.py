def test_apply_commits_the_replay_on_a_branch_and_leaves_the_tag_alone(world):
    write_folder(world)
    source = world["source"]
    git(source, "branch", "port", "T1")
    before = git(source, "rev-parse", "T1^{tree}").decode().strip()
    commit = br.apply_to_branch(source, "T1", world["folder"], "port")
    assert git(source, "rev-parse", "refs/heads/port").decode().strip() == commit
    assert git(source, "rev-parse", "T1^{tree}").decode().strip() == before
    assert git(source, "show", "port:third_party/rust/wgpu-a/src/lib.rs").decode() == A20
    assert git(source, "show", "port:third_party/rust/wgpu-a/src/new.rs").decode() == "pub fn new() {}\n"
    # the diff of the branch against the tag is the replay's patch, byte for byte
    diff = git(source, "diff", "--binary", "--full-index", "--no-renames", "T1", "port", "--", "Cargo.lock", "third_party/rust/wgpu-a/src/lib.rs")
    result = br.replay(source, "T1", world["folder"])
    assert diff == result.sections["Cargo.lock"] + result.sections["third_party/rust/wgpu-a/src/lib.rs"]


def test_a_port_replays_the_backport_and_the_vendored_conflicts_of_the_merge_are_gone(series, capsys):
    """`port` merges every folder three-way, then replaces the vendored paths of a backport by the replay of its commits
    on the new tag: the checksum files that the merge left in conflict are rewritten by the tool, not resolved."""
    source = series["source"]
    assert engine.port(source, "T1", "T2", "port/T2", force=False) == 0
    out = capsys.readouterr().out
    assert "REPLAY fingerprint/synthetic: wgpu %s, 1 commits already in the revision" % R2[:10] in out
    assert "CONFLICT" not in out
    result = br.replay(source, "T2", series["folder"])
    diff = git(source, "diff", "--binary", "--full-index", "--no-renames", "T2", "port/T2", "--", *sorted(result.sections))
    assert diff == result.patch
    assert git(source, "show", "port/T2:third_party/rust/wgpu-a/src/new.rs").decode() == "pub fn new() {}\n"


def test_a_port_reports_the_commit_that_does_not_apply_on_the_new_tag(series, capsys):
    write(series["source"], "third_party/rust/wgpu-a/src/lib.rs", A10.replace("{ 2 }", "{ 2000 }"))
