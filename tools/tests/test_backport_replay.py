def test_a_hook_in_a_file_of_mozilla_is_kept_as_it_is(world):
    result = write_folder(world)
    hook = (b"diff --git a/gfx/x.rs b/gfx/x.rs\nindex 1111111111111111111111111111111111111111..2222222222222222222222222222222222222222 100644\n"
            b"--- a/gfx/x.rs\n+++ b/gfx/x.rs\n@@ -1 +1,2 @@\n a\n+pub mod ours; // STEALTH-HOOK(fingerprint/synthetic)\n")
