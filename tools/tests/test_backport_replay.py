R1 = "1" * 40
R2 = "2" * 40
ENV = dict(os.environ, GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1", GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@users.noreply.github.com",
           GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@users.noreply.github.com")

LIB_A = "fn a() -> u32 { 1 }\nfn b() -> u32 { 2 }\nfn c() -> u32 { 3 }\nfn d() -> u32 { 4 }\nfn e() -> u32 { 5 }\n"
A10 = LIB_A.replace("{ 1 }", "{ 10 }")                      # what the first commit makes of it
A20 = A10.replace("{ 2 }", "{ 20 }")                        # and the second
LIB_B = "pub fn b() {}\n"
CARGO_A = '[package]\nname = "wgpu-a"\nversion = "1.0.0"\n\n[dependencies.alpha]\nversion = "0.1"\n\n[dependencies.gamma]\nversion = "0.3"\noptional = true\n'
CARGO_A_UPSTREAM = '[package]\nname = "wgpu-a"\n\n[dependencies]\nalpha.workspace = true\ngamma = { workspace = true, optional = true }\n'
LOCK = ('# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "alpha"\nversion = "0.1.0"\n\n'
        '[[package]]\nname = "beta"\nversion = "0.2.0"\n\n[[package]]\nname = "wgpu-a"\nversion = "1.0.0"\n'
        'source = "git+https://github.com/gfx-rs/wgpu?rev=%s#%s"\ndependencies = [\n "alpha",\n "gamma",\n]\n\n'
        '[[package]]\nname = "gamma"\nversion = "0.3.0"\n')
LOCK_UPSTREAM = ('[[package]]\nname = "alpha"\nversion = "0.1.0"\n\n[[package]]\nname = "wgpu-a"\nversion = "1.0.0"\n'
                 'dependencies = [\n "alpha",\n "gamma",\n]\n\n[[package]]\nname = "gamma"\nversion = "0.3.0"\n')
BINDINGS = ('[dependencies.wgc]\npackage = "wgpu-core"\ngit = "https://github.com/gfx-rs/wgpu"\nrev = "%s"\n\n'
            '[dependencies.wgt]\npackage = "wgpu-types"\ngit = "https://github.com/gfx-rs/wgpu"\nrev = "%s"\n')
WORKSPACE = {"beta": {"version": "0.2", "features": ["base"]}}


def git(cwd, *args, input=None) -> bytes:
    done = subprocess.run(["git", "-c", "core.autocrlf=false", *args], cwd=cwd, env=ENV, input=input, capture_output=True)
    assert done.returncode == 0, done.stderr.decode()
    return done.stdout


def write(root: Path, rel: str, text: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode())


def checksummed(root: Path, crate: str) -> None:
    """(Re)writes a crate's checksum file from its files: only to build the tags, the tests below do not take their
    expectation from it."""
    d = root / "third_party" / "rust" / crate
    old = {"files": {}, "package": "p" * 64}
    (d / ".cargo-checksum.json").write_bytes(regen_checksums.render(old, regen_checksums.read_dir(str(d))))


def make_tree(root: Path, revision: str, lib_a: str = LIB_A) -> None:
    write(root, "gfx/wgpu_bindings/Cargo.toml", BINDINGS % (revision, revision))
    write(root, "third_party/rust/wgpu-a/src/lib.rs", lib_a)
    write(root, "third_party/rust/wgpu-a/Cargo.toml", CARGO_A)
    write(root, "third_party/rust/naga-b/src/lib.rs", LIB_B)
    write(root, "Cargo.lock", LOCK % (revision, revision))
    checksummed(root, "wgpu-a")
    checksummed(root, "naga-b")


def commit_tag(root: Path, tag: str) -> None:
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", tag)
    git(root, "tag", tag)


def build_world(tmp_path):
    """A source repository with tags T1 (vendors R1) and T2 (vendors R2, which contains the first pick), and a folder."""
    source = tmp_path / "source"
    source.mkdir()
    git(source, "init", "-q")
    make_tree(source, R1)
    commit_tag(source, "T1")
    make_tree(source, R2, A10)
    commit_tag(source, "T2")
    # upstream, in its own layout: the base is what R1 vendors
    up = tmp_path / "upstream"
    up.mkdir()
    git(up, "init", "-q")
    write(up, "wgpu-a/src/lib.rs", LIB_A)
    write(up, "wgpu-a/Cargo.toml", CARGO_A_UPSTREAM)
    write(up, "naga-b/src/lib.rs", LIB_B)
    write(up, "Cargo.lock", LOCK_UPSTREAM)
    write(up, "tests/t.rs", "// a test\n")
    git(up, "add", "-A")
    git(up, "commit", "-q", "-m", "base")
    base = git(up, "rev-parse", "HEAD").decode().strip()
    # 1: a pick
    write(up, "wgpu-a/src/lib.rs", A10)
    git(up, "commit", "-qam", "pick: one is ten")
    # 2: ours, on top of it (its context holds the line the pick wrote)
    write(up, "wgpu-a/src/lib.rs", A20)
    git(up, "commit", "-qam", "fix: two is twenty")
    # 3: a pick that adds a file, a dependency (workspace form) and its lock entry, and changes another crate
    write(up, "wgpu-a/src/new.rs", "pub fn new() {}\n")
    write(up, "naga-b/src/lib.rs", LIB_B + "pub fn b2() {}\n")
    write(up, "wgpu-a/Cargo.toml", CARGO_A_UPSTREAM.replace("gamma =", 'beta = { workspace = true, features = ["x"] }\ngamma ='))
    write(up, "Cargo.lock", LOCK_UPSTREAM.replace(' "gamma",\n', ' "beta",\n "gamma",\n').replace(' "beta",\n "gamma"', ' "alpha",\n "beta",\n "gamma"', 0))
    write(up, "Cargo.lock", LOCK_UPSTREAM.replace(' "alpha",\n "gamma",', ' "alpha",\n "beta",\n "gamma",'))
    git(up, "add", "-A")
    git(up, "commit", "-qm", "pick: a file, a dependency")
    # 4: a test only
    write(up, "tests/t.rs", "// a test\n// another\n")
    git(up, "commit", "-qam", "test: another")
    patches = git(up, "format-patch", "--no-signature", "--stdout", "%s..HEAD" % base)
    folder = tmp_path / "series" / "fingerprint" / "synthetic"
    (folder / "commits").mkdir(parents=True)
    kinds = ["upstream", "ours", "upstream", "test"]
    shas = git(up, "rev-list", "--reverse", "%s..HEAD" % base).decode().split()
    chunks = [c for c in patches.split(b"\nFrom ") if c.strip()]
    chunks = [(c if c.startswith(b"From ") else b"From " + c) for c in chunks]
    assert len(chunks) == 4
    entries = []
    for i, (chunk, kind, sha) in enumerate(zip(chunks, kinds, shas), 1):
        chunk = chunk if chunk.endswith(b"\n") else chunk + b"\n"
        name = "commits/%04d-%s.patch" % (i, kind)
        (folder / name).write_bytes(chunk)
        entry = {"file": name, "sha256": hashlib.sha256(chunk).hexdigest(), "kind": kind}
        if kind == "upstream":
            entry["upstream_sha"] = sha
        entry["contained_in"] = None
        entries.append(entry)
    record = {"upstream": "https://example.invalid/wgpu", "vendored": R1, "workspace_dependencies": WORKSPACE,
              "commits": entries, "drop_when": "never"}
    (folder / "BACKPORT.json").write_text(json.dumps(record), encoding="utf-8")
    return {"source": source, "folder": folder, "record": record, "series": tmp_path / "series"}


@pytest.fixture(scope="module")
def built_world(tmp_path_factory):
    root = tmp_path_factory.mktemp("built")
    build_world(root)
    return root


