"""port-04: vendored code is carried as the commits it needs, replayed on the revision the tag vendors.

A synthetic Firefox tree (a git repository with a tag) holds two vendored crates in Mozilla's form (`cargo vendor`
Cargo.toml, `.cargo-checksum.json`, a Cargo.lock with a git source) at a revision R. A synthetic upstream repository
in upstream's layout makes the commits (git format-patch): one pick, one of ours that builds on it, one that adds a file, a
dependency and a lock entry, one that is a test only. The tests replay them and break one thing at a time.

    python -m pytest tools/tests/test_backport_replay.py
"""
