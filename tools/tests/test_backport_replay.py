def test_the_commits_are_replayed_in_order_and_the_test_only_one_is_skipped(world):
    result = br.replay(world["source"], "T1", world["folder"])
    assert [c.status for c in result.commits] == ["applied", "applied", "applied", "tests"]
    assert result.conflicts == []
    # the second commit's context holds the line the first one wrote: it applies only after it
