def write_folder(w):
    """hooks.patch, src/ and MANIFEST.json as export would write them for the replay on T1."""
    result = br.replay(w["source"], "T1", w["folder"])
    folder = w["folder"]
    (folder / "hooks.patch").write_bytes(br.expected_patch(result, b""))
    for path, (mode, data) in result.added.items():
        write_bytes = folder / "src" / path
        write_bytes.parent.mkdir(parents=True, exist_ok=True)
        write_bytes.write_bytes(data)
    manifest = {"modified": sorted(result.sections), "added": {p: m for p, (m, _d) in sorted(result.added.items())}, "inventory": []}
    (folder / "MANIFEST.json").write_text(json.dumps(manifest), encoding="utf-8")
    return result


def sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


